// Builds data/i18n/content/index.ts from the translation files in that folder.
// File names are <dataset>.<locale>.json. Run automatically before `next build`.
import { readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const dir = join(dirname(fileURLToPath(import.meta.url)), "..", "data", "i18n", "content");
const files = readdirSync(dir).filter((f) => f.endsWith(".json")).sort();
const entries = files.map((file) => {
  const [dataset, locale] = file.replace(/\.json$/, "").split(/\.(?=[^.]+$)/);
  return { file, dataset, locale, id: `${dataset}_${locale}`.replace(/[^A-Za-z0-9_]/g, "_") };
});
const datasets = [...new Set(entries.map((e) => e.dataset))];
let out = "// GENERATED by scripts/generate-content-index.mjs — do not edit.\n";
for (const e of entries) out += `import ${e.id} from "./${e.file}";\n`;
out += "\nexport const translationFiles: Record<string, Record<string, unknown>> = {\n";
for (const dataset of datasets) {
  out += `  ${JSON.stringify(dataset)}: {\n`;
  for (const e of entries.filter((x) => x.dataset === dataset)) out += `    ${JSON.stringify(e.locale)}: ${e.id},\n`;
  out += "  },\n";
}
out += "};\n";
writeFileSync(join(dir, "index.ts"), out);
console.log(`content index: ${entries.length} files, ${datasets.length} datasets`);
